create table account (
    id bigint generated by default as identity primary key,
    email varchar(255) not null,
    password_hash varchar(255) not null,
    display_name varchar(120) not null,
    role varchar(20) not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_account_email unique (email),
    constraint chk_account_role check (role in ('USER', 'ADMIN'))
);

create table refresh_token (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    token_hash varchar(64) not null,
    expires_at timestamp with time zone not null,
    revoked_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_refresh_token_hash unique (token_hash),
    constraint fk_refresh_token_account foreign key (account_id) references account (id)
);

create index idx_refresh_token_account_id on refresh_token (account_id);

create table product (
    id bigint generated by default as identity primary key,
    sku varchar(64) not null,
    name varchar(160) not null,
    description varchar(500),
    unit_price numeric(19, 2) not null,
    available_stock integer not null,
    version bigint not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_product_sku unique (sku),
    constraint chk_product_price_non_negative check (unit_price >= 0),
    constraint chk_product_stock_non_negative check (available_stock >= 0)
);

create table purchase_order (
    id bigint generated by default as identity primary key,
    order_number varchar(40) not null,
    owner_id bigint not null,
    status varchar(20) not null,
    total_amount numeric(19, 2) not null,
    version bigint not null default 0,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    created_by varchar(255),
    updated_by varchar(255),
    constraint uk_purchase_order_number unique (order_number),
    constraint fk_purchase_order_owner foreign key (owner_id) references account (id),
    constraint chk_purchase_order_status check (status in ('CREATED', 'PAID', 'CANCELLED', 'SHIPPED', 'COMPLETED')),
    constraint chk_purchase_order_total_non_negative check (total_amount >= 0)
);

create index idx_purchase_order_owner_id on purchase_order (owner_id);
create index idx_purchase_order_status on purchase_order (status);

create table order_line (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    product_id bigint not null,
    product_sku_snapshot varchar(64) not null,
    product_name_snapshot varchar(160) not null,
    unit_price_snapshot numeric(19, 2) not null,
    quantity integer not null,
    line_total numeric(19, 2) not null,
    constraint fk_order_line_order foreign key (order_id) references purchase_order (id),
    constraint fk_order_line_product foreign key (product_id) references product (id),
    constraint chk_order_line_quantity_positive check (quantity > 0),
    constraint chk_order_line_total_non_negative check (line_total >= 0)
);

create index idx_order_line_order_id on order_line (order_id);
create index idx_order_line_product_id on order_line (product_id);

create table order_status_history (
    id bigint generated by default as identity primary key,
    order_id bigint not null,
    previous_status varchar(20),
    new_status varchar(20) not null,
    transition_at timestamp with time zone not null,
    actor_email varchar(255),
    reason varchar(255),
    constraint fk_order_status_history_order foreign key (order_id) references purchase_order (id),
    constraint chk_order_status_history_previous_status check (
        previous_status is null or previous_status in ('CREATED', 'PAID', 'CANCELLED', 'SHIPPED', 'COMPLETED')
    ),
    constraint chk_order_status_history_new_status check (
        new_status in ('CREATED', 'PAID', 'CANCELLED', 'SHIPPED', 'COMPLETED')
    )
);

create index idx_order_status_history_order_transition on order_status_history (order_id, transition_at);
